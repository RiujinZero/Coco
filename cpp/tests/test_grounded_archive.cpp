#include "laminar/grounded_session.h"
#include <iostream>
using namespace laminar::reasoning;
void check(bool good,const std::string& message){if(!good)throw std::runtime_error(message);}
void feed(GroundedSession& s,const std::string& text,bool generated=false){for(uint8_t c:text)s.observe(c,generated);}
std::shared_ptr<GroundedSession> fixture() {
    auto r=std::make_shared<LanguageReasoner>(0);
    r->environment_dialogue=r->grounded_requests=r->grounded_events=r->uncertain_events=r->partial_observation=true;
    r->memory.unique_enabled=true;r->world_budget=4096;
    r->forms={{"who has the $0 now ",0},{"does $0 have the $1 ",1}};r->memory.procedures={{0,{17,9}},{1,{3,11,9}}};
    for(int i=0;i<8;++i) {
        auto a="actor"+std::to_string(i),o="item"+std::to_string(i);EventGrounding::World before{{o,1,"old"},{"spare",1,a}};
        check(r->events.teach_transition(a+" has the "+o+".",before,EventGrounding::update(before,1,2,o,a),i),"fixture event");
    }
    auto s=std::make_shared<GroundedSession>(r);s->teachers={"teacher","other_teacher"};s->enable_archive();return s;
}
void start(GroundedSession& s) {feed(s,"\n<|endofdialogue|>\nCONTEXT: ada has the key.\nCONTEXT: ben has the coin.\nCONTEXT: cy has the pen.\n");}
std::string ask(GroundedSession& s,const std::string& q="Who has the key now?") {
    feed(s,"\nUSER: "+q+"\nASSISTANT:");return LanguageReasoner::trim(s.reader->reply);
}
std::string historical(GroundedSession& s,uint64_t episode,uint64_t report,const std::string& q) {
    auto view=s.archive->at(episode,report);check(bool(view),"missing archived view");view->question=q;view->prepare();return LanguageReasoner::trim(view->reply);
}
int main() {
    const std::string frame="the $0 was logged beside $1 ";
    auto s=fixture();start(*s);feed(*s,"ENVIRONMENT: The key was logged beside cy.\n");
    check(s->teach(*s->feedback_anchor(1),0,"Who has the key now?","ada","teacher"),"first lesson");
    check(ask(*s)=="ada","plausible mistaken lesson");
    start(*s);feed(*s,"ENVIRONMENT: The coin was logged beside ada.\n");
    check(s->teach(*s->feedback_anchor(1),0,"Who has the coin now?","ada","teacher"),"later contradiction receipt");
    check(!s->archive->consistent&&ask(*s)=="I do not know.","cross-episode contradiction not withheld");
    // A later physical event remains later when an old lesson is corrected.
    feed(*s,"\nENVIRONMENT: ben has the key.\n");
    auto old=s->archived_anchor(1,1);check(bool(old),"old receipt unavailable during conflict");auto revision=s->archive->revision;
    check(!s->teach_archived(*old,0,"Who has the key now?","cy","stranger",GroundedSession::REVISE_FEEDBACK),"unverified old teacher");
    check(!s->teach_archived(*old,0,"Who has the key now?","cy","teacher",GroundedSession::REVISE_FEEDBACK,0,true),"generated old teacher");
    check(!s->teach_archived(*old,0,"Who has the key now?","cy","other_teacher",GroundedSession::REVISE_FEEDBACK),"different teacher revised old evidence");
    check(s->archive->revision==revision,"rejected evidence changed archive");
    auto episode=s->reader->episode_revision,observation=s->reader->observation_revision;
    check(s->teach_archived(*old,0,"Who has the key now?","cy","teacher",GroundedSession::REVISE_FEEDBACK),"old lesson correction: "+s->teaching_status);
    check(s->archive->consistent&&ask(*s)=="ben","replay did not preserve current later event");
    check(s->reader->episode_revision==episode&&s->reader->observation_revision==observation,"teaching forged physical observation/reset");
    check(historical(*s,1,1,"Who has the key now?")=="cy","discarded interpretation not restored");
    check(historical(*s,2,1,"Who has the key now?")=="ada","physical facts crossed episode boundary");
    check(s->reader->observation_language.frames.at(frame).scenes.size()==2,"duplicate local report IDs collapsed support");
    check(!s->teach_archived(*old,1,"Who has the key now?","cy","teacher"),"stale archive anchor accepted");
    auto clone=s->clone();auto before=s->archive->revision;
    check(clone->teach_archived(*clone->archived_anchor(1,1),0,"Who has the key now?","unknown","teacher",GroundedSession::WITHDRAW_FEEDBACK,1),"old feedback withdrawal");
    check(clone->reader->observation_language.frames.at(frame).scenes.size()==1&&s->reader->observation_language.frames.at(frame).scenes.size()==2,"clone or support isolation");
    check(s->archive->revision==before&&ask(*s)=="ben","clone altered live archive");
    check(clone->teach_archived(*clone->archived_anchor(1,1),0,"Who has the key now?","cy","teacher",GroundedSession::REVISE_FEEDBACK,2),"restore old feedback");
    check(clone->reader->observation_language.signature()==s->reader->observation_language.signature(),"restoration inflated support");
    feed(*s,"\n<|endofdialogue|>\nENVIRONMENT: cy has the key.\n",true);
    check(s->archive->revision==before&&s->resets==2,"generated bytes altered archive");
    // Old feedback can arrive before the new episode has finished receiving its
    // initial context. Publishing replay must not convert remaining context into
    // forbidden late observations or clear an incomplete input segment.
    feed(*s,"\n<|endofdialogue|>\nCONTEXT: ada has the key.\nCONTEXT: ben has");
    auto segment=s->reader->segment;
    check(s->teach_archived(*s->archived_anchor(1,1),0,"Who has the key now?","cy","teacher",GroundedSession::REVISE_FEEDBACK,1),"teaching during initial context");
    check(!s->journal.base&&s->reader->segment==segment,"teaching closed or cleared initial context");
    feed(*s," the coin.\nCONTEXT: cy has the pen.\n");
    check(ask(*s,"Who has the coin now?")=="ben"&&s->initial_context.size()==3,"remaining context was lost");
    auto limited=s->clone();size_t stored=0;
    for(const auto& [id,e]:limited->archive->episodes)stored+=GroundedArchive::storage_bytes(e);
    auto limit_before=limited->archive->revision;
    auto receipt_before=GroundedArchive::signature(limited->archive->episodes.at(1));
    limited->archive->text_budget=stored;
    auto limit_anchor=*limited->archived_anchor(1,1);
    check(!limited->teach_archived(limit_anchor,99,"Who has the key now?","cy","teacher"),"remote receipt bypassed storage budget");
    check(limited->teaching_status=="archive_capacity"&&limited->archive->revision==limit_before&&!limited->archive->truncated,"rejected receipt changed archive version");
    check(GroundedArchive::signature(limited->archive->episodes.at(1))==receipt_before&&ask(*limited,"Who has the coin now?")=="ben","rejected receipt changed accepted evidence or knowledge");
    limited->archive->text_budget=stored+1024;
    check(limited->teach_archived(limit_anchor,99,"Who has the key now?","cy","teacher"),"rejected capacity edit was not retryable");
    // Two uncertain frames have correlated meanings: at least one must remove
    // the self-possession fact. Joining marginal candidates would incorrectly
    // admit the pair IGNORE/IGNORE and spoil the definite historical 'no'.
    auto correlated=fixture();feed(*correlated,"\n<|endofdialogue|>\nCONTEXT: key has the key.\nENVIRONMENT: The key was blurred.\nENVIRONMENT: The key was shaded.\n");
    check(correlated->teach(*correlated->feedback_anchor(2),0,"Does key have the key?","no","teacher"),"correlation lesson");
    check(correlated->archive->consistent,"correlation search failed: "+correlated->archive->status);
    start(*correlated);check(ask(*correlated)=="ada","fresh world reset");
    check(historical(*correlated,1,2,"Does key have the key?")=="no","cross-frame correlations lost across reset");
    // A capacity failure cannot silently discard old evidence and publish a
    // convenient subset on the next reset.
    auto bounded=fixture();bounded->archive->episode_budget=1;start(*bounded);check(ask(*bounded)=="ada","bounded first episode");
    start(*bounded);check(ask(*bounded)=="I do not know."&&bounded->archive->truncated,"capacity did not withhold");
    start(*bounded);check(ask(*bounded)=="I do not know.","reset hid lost provenance");
    std::cout<<"cross-episode correction, correlated meanings, physical isolation, support retraction, authority and bounded archive contracts passed\n";
}
